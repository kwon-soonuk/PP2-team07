ACCOUNTS = {
    "student1": "학생",
    "student2": "학생",
    "admin1": "관리자"
}
# 1-1) 계정 딕셔너리 ACCOUNTS 를 만든다.
#      키 = 계정 문자열, 값 = 역할 문자열
#      1차 계정 3개: student1 → "학생", student2 → "학생", admin1 → "관리자"
#      모양은 practice/role_demo.py 의 accounts 와 같다 (PP 8장 딕셔너리)
#      ※ 2차에서 student8 까지 늘릴 때 여기만 고치면 되게, 딕셔너리는 함수 밖(파일 위쪽)에 둔다

def get_role(account):
    if account in ACCOUNTS:
        return ACCOUNTS[account]
    else:
        return None
    # 1-2) account 가 ACCOUNTS 에 있으면 그 역할을, 없으면 None 을 return 한다.
    #      방법 A: if 문으로 '키가 딕셔너리 안에 있는지' 검사 (in) → 있으면 값, 없으면 None
    #      방법 B: 딕셔너리 메서드 하나로 한 줄에 끝난다
    #              (없는 키를 물어도 KeyError 대신 None 을 돌려주는 메서드 — PP 8장)
    #      둘 중 편한 걸로. 교수님이 물으면 둘의 차이를 말할 수 있게 해 둔다.
    #      ※ 앞뒤 공백 제거(strip)는 여기서 하지 않는다 — 입력을 받는 main.py 가 한다

if __name__ == "__main__":
    print(get_role("student1"))  # "학생"
    print(get_role("admin1"))    # "관리자"
    print(get_role("abc"))       # None
