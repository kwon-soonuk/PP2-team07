#   get_role(account) → "학생" / "관리자" / None. 화면 출력은 main.py 몫

ACCOUNTS = {
    "student1": "학생",
    "student2": "학생",
    "student3": "학생",
    "student4": "학생",
    "student5": "학생",
    "student6": "학생",
    "student7": "학생",
    "student8": "학생",
    "admin1": "관리자"
}

def get_role(account):
    if account in ACCOUNTS:
        return ACCOUNTS[account]
    else:
        return None

if __name__ == "__main__":
    print(get_role("student1"))  # "학생"
    print(get_role("admin1"))    # "관리자"
    print(get_role("abc"))       # None
